import {afterEach,expect,it,vi} from 'vitest'
const f=vi.hoisted(()=>({direct:true,epoch:0,loading:false,change:null as null|(()=>void)}))
vi.mock('./collection-config',()=>({collectionMode:()=>true,collectionScope:()=>`fixture-profile:${f.epoch}`,collectionGeneration:()=>f.epoch,collectionStatus:()=>({loading:f.loading}),loadCollectionConfig:async()=>{},onCollectionChange:(fn:()=>void)=>{f.change=fn}}))
vi.mock('./market-provider',()=>({directOkxMode:()=>f.direct}))
function transport(){return {state:'connected',connect:vi.fn(),disconnect:vi.fn(),setQuoteSymbols:vi.fn(),setDepthSymbols:vi.fn(),setChartSubscription:vi.fn(),observeVersion:vi.fn(),hasFreshQuote:()=>true,hasFreshDepth:()=>true,hasFreshCandle:()=>true,hasFreshTrades:()=>true,onMessage:vi.fn(()=>vi.fn()),onStateChange:vi.fn(()=>vi.fn()),onQuoteStateChange:vi.fn(()=>vi.fn()),onQuoteFreshnessChange:vi.fn(()=>vi.fn())}}
const sockets=vi.hoisted(()=>({direct:null as any,collection:null as any}))
vi.mock('./okx-snippet-ws',()=>({getOkxSnippetWebSocket:()=>sockets.direct}))
vi.mock('./collection-stream',()=>({getCollectionStream:()=>sockets.collection}))
afterEach(()=>{vi.resetModules();f.direct=true;f.epoch=0;f.loading=false})
it('retains subscribers and requested symbols while switching both directions; retired frames are ignored',async()=>{
  sockets.direct=transport();sockets.collection=transport()
  const {getPublicMarketSocket}=await import('./public-market')
  const socket=getPublicMarketSocket(),received=vi.fn()
  socket.setQuoteSymbols(['btcusdt']);socket.setDepthSymbols(['ethusdt']);socket.setChartSubscription([{symbol:'btcusdt',period:'1m'}]);socket.onMessage(received)
  socket.connect();await Promise.resolve();await Promise.resolve()
  expect(sockets.direct.connect).toHaveBeenCalledOnce()
  const stale=sockets.direct.onMessage.mock.calls[0][0]
  f.direct=false;f.epoch++;f.change!()
  expect(getPublicMarketSocket()).toBe(socket)
  expect(sockets.direct.disconnect).toHaveBeenCalledOnce()
  expect(sockets.collection.connect).toHaveBeenCalledOnce()
  expect(sockets.collection.setQuoteSymbols).toHaveBeenLastCalledWith(['btcusdt'])
  expect(sockets.collection.setDepthSymbols).toHaveBeenLastCalledWith(['ethusdt'])
  expect(sockets.collection.setChartSubscription).toHaveBeenLastCalledWith([{symbol:'btcusdt',period:'1m'}])
  stale({type:'quote',data:[]});expect(received).not.toHaveBeenCalled()
  sockets.collection.onMessage.mock.calls[0][0]({type:'quote',data:[]});expect(received).toHaveBeenCalledOnce()
  f.direct=true;f.epoch++;f.change!()
  expect(sockets.collection.disconnect).toHaveBeenCalledOnce();expect(sockets.direct.connect).toHaveBeenCalledTimes(2)
  socket.disconnect();f.epoch++;f.change!();expect(sockets.direct.connect).toHaveBeenCalledTimes(2)
})
it('disconnects during scope configuration load without temporarily dialing either provider',async()=>{
  sockets.direct=transport();sockets.collection=transport()
  const {getPublicMarketSocket}=await import('./public-market')
  const socket=getPublicMarketSocket();socket.connect();await Promise.resolve();await Promise.resolve()
  f.loading=true;f.epoch++;f.change!()
  expect(sockets.direct.disconnect).toHaveBeenCalledOnce();expect(sockets.collection.connect).not.toHaveBeenCalled()
  f.loading=false;f.direct=false;f.epoch++;f.change!()
  expect(sockets.collection.connect).toHaveBeenCalledOnce()
  socket.disconnect()
})
