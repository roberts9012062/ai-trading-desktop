import { afterEach, expect, it, vi } from 'vitest'
afterEach(() => { vi.unstubAllGlobals(); vi.resetModules() })
it('loads the OKX instrument catalog without a collection key or business server', async () => {
  vi.stubGlobal('window', {})
  const fetch = vi.fn().mockResolvedValue(new Response(JSON.stringify({code:'0',data:[{instId:'BTC-USDT-SWAP',state:'live',settleCcy:'USDT',ctType:'linear',tickSz:'0.1',lotSz:'0.01',minSz:'0.01',ctVal:'0.01',ctValCcy:'BTC'}]})))
  vi.stubGlobal('fetch',fetch)
  const { directSymbols } = await import('./okx-direct')
  await expect(directSymbols()).resolves.toEqual([{symbol:'BTC-USDT-SWAP',name:'BTC 永续',tick_size:'0.1',lot_size:'0.01',min_size:'0.01',contract_value:'0.01',contract_value_currency:'BTC'}])
  expect(fetch.mock.calls[0][0]).toBe('/__okx_direct__/api/v5/public/instruments?instType=SWAP')
})
it('maps real candle volume, closed status and an exclusive historical cursor', async () => {
  vi.stubGlobal('window', {})
  const fetch = vi.fn().mockResolvedValue(new Response(JSON.stringify({code:'0',data:[['1792800000000','100','103','99','102','20','0.2','20.4','1']]})))
  vi.stubGlobal('fetch',fetch)
  const { directData } = await import('./okx-direct')
  const data = await directData({symbol:'BTC-USDT-SWAP',operation:'history',resolution:'1',count:300,end:1792800059})
  expect(data.records[0]).toMatchObject({timestamp:1792800000,volume:0.2,contract_volume:20,quote_volume:20.4,closed:true})
  expect(fetch.mock.calls[0][0]).toContain('after=1792800060000')
  expect(fetch.mock.calls[0][0]).toContain('limit=300')
})
it('retains exact trade milliseconds and declared contract volume units', async () => {
  vi.stubGlobal('window', {})
  vi.stubGlobal('fetch',vi.fn().mockResolvedValue(new Response(JSON.stringify({code:'0',data:[{tradeId:'t1',ts:'1792800181123',px:'100',sz:'2',side:'sell'}]}))))
  const { directData } = await import('./okx-direct')
  const data = await directData({symbol:'BTC-USDT-SWAP',operation:'ticks',count:100})
  expect(data.ticks[0]).toMatchObject({timestamp:1792800181.123,trade_id:'t1',volume:2,volume_unit:'contracts',side:'sell'})
})
it('rejects malformed requests and never falls back to a relay after OKX rejects a request', async () => {
  vi.stubGlobal('window', {})
  const fetch = vi.fn().mockResolvedValue(new Response(JSON.stringify({code:'50011',msg:'rate limited',data:[]})))
  vi.stubGlobal('fetch',fetch)
  const { directData } = await import('./okx-direct')
  await expect(directData({symbol:'BTC-USDT-SWAP',operation:'history',resolution:'evil',count:300})).rejects.toThrow()
  expect(fetch).not.toHaveBeenCalled()
  await expect(directData({symbol:'BTC-USDT-SWAP',operation:'ticks',count:100})).rejects.toThrow('50011')
  expect(fetch).toHaveBeenCalledOnce()
})
it('uses official private endpoints for the selected exchange environment', async () => {
  const {directPrivateSocketAddress} = await import('./market-provider')
  expect(directPrivateSocketAddress(false)).toBe('wss://ws.okx.com/ws/v5/private')
  expect(directPrivateSocketAddress(true)).toBe('wss://wspap.okx.com/ws/v5/private')
})
