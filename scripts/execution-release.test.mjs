import {test} from 'node:test'
import assert from 'node:assert/strict'
import * as fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import {createHash} from 'node:crypto'
import {verifyReleaseExecutionArtifact} from './fetch-execution-worker.mjs'

const hash=value=>createHash('sha256').update(value).digest('hex')
async function fixture(){
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'execution-release-'))
  const runtime=path.join(root,'resources','execution-worker')
  await fs.mkdir(runtime,{recursive:true});await fs.mkdir(path.join(root,'src-tauri'))
  const binary=Buffer.from('synthetic-test-native-binary')
  await fs.writeFile(path.join(runtime,'execution-worker.exe'),binary)
  const manifest=JSON.stringify({protocol:1,entry:'execution-worker.exe',build_id:'test-1',files:[{path:'execution-worker.exe',size:binary.length,sha256:hash(binary)}]})
  await fs.writeFile(path.join(runtime,'manifest.json'),manifest)
  const lock={protocol:1,tag:'executor-runtime-test-1',asset:'test-1.zip',build_id:'test-1',sha256:'a'.repeat(64),manifest_sha256:hash(manifest)}
  await fs.writeFile(path.join(root,'execution-worker.lock.json'),JSON.stringify(lock))
  await fs.writeFile(path.join(root,'src-tauri','tauri.conf.json'),JSON.stringify({bundle:{resources:{'../resources/execution-worker':'execution-worker'}}}))
  return {root,runtime,lock}
}
async function clean(value){
  // Only explicit files generated by the fixture, never recursive cleanup.
  for(const file of ['execution-worker.exe','manifest.json'])await fs.unlink(path.join(value.runtime,file))
  await fs.rmdir(value.runtime);await fs.rmdir(path.join(value.root,'resources'))
  await fs.unlink(path.join(value.root,'src-tauri','tauri.conf.json'));await fs.rmdir(path.join(value.root,'src-tauri'))
  try{await fs.unlink(path.join(value.root,'execution-worker.lock.json'))}catch(error){if(error.code!=='ENOENT')throw error}
  await fs.rmdir(value.root)
}
test('release requires a pinned and completely verified worker mapped into the installer',async()=>{
  const value=await fixture()
  try{
    assert.equal((await verifyReleaseExecutionArtifact(value.root)).build_id,'test-1')
    await fs.writeFile(path.join(value.root,'src-tauri','tauri.conf.json'),JSON.stringify({bundle:{resources:{'../resources/native-engine':'native-engine'}}}))
    await assert.rejects(verifyReleaseExecutionArtifact(value.root),/安装包资源/)
  }finally{await clean(value)}
})
test('release rejects missing pins and tampered installed files before signing',async()=>{
  const value=await fixture()
  try{
    await fs.writeFile(path.join(value.runtime,'execution-worker.exe'),'changed')
    await assert.rejects(verifyReleaseExecutionArtifact(value.root),/长度不匹配|摘要不匹配/)
    await fs.unlink(path.join(value.root,'execution-worker.lock.json'))
    await assert.rejects(verifyReleaseExecutionArtifact(value.root),/锁定文件/)
  }finally{await clean(value)}
})
